"""Owned data-only manual test pack. No software downloads or boot/OS payloads."""
from pathlib import Path
from io import BytesIO
import hashlib,zipfile,tarfile,gzip,lzma,sys,subprocess,os,json
R=Path(__file__).resolve().parents[1];out=R/'artifacts/manual-test-files';out.mkdir(exist_ok=True)
def put(name,data):
 p=out/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
small={'hello.txt':b'USB Workbench manual test.\n','عربي.txt':'اختبار USB باللغة العربية.\n'.encode(),'empty.txt':b'','nested/inside.txt':b'Nested file stays the same.\n'}
for n,b in small.items():put('small/'+n,b)
raw=bytes(range(256))*32768;put('raw-8MiB.img',raw);put('raw-8MiB.img.gz',gzip.compress(raw,mtime=0));put('raw-8MiB.img.xz',lzma.compress(raw))
with zipfile.ZipFile(out/'samples.zip','w',zipfile.ZIP_DEFLATED) as z:
 for n,b in small.items():z.writestr(n,b)
for suffix,mode in [('gz','w:gz'),('xz','w:xz')]:
 with tarfile.open(out/('samples.tar.'+suffix),mode) as t:
  for n,b in small.items():i=tarfile.TarInfo(n);i.size=len(b);i.mtime=0;t.addfile(i,BytesIO(b))
sys.path.insert(0,str(R/'tools'));from archive_password_fixture import make
put('password.zip',make(b'fixture-only',b'Owned encrypted test data\n'*50))
# These previously verified owned fixtures contain generated bytes only, not downloaded OS content.
for src,dest in [('fat-image-fixtures/fat16.img','samples/fat16.img'),('fat-image-fixtures/fat16-mbr.img','samples/fat16-mbr.img'),('dmg-fixtures/owned.dmg','samples/data.dmg'),('dmg-fixtures/expected.img','samples/dmg-expected.img'),('chd-fixtures/2048.chd','samples/data.chd'),('chd-fixtures/2048.expected.img','samples/chd-expected.img')]:put(dest,(R/'artifacts'/src).read_bytes())
put('expected-fat/ملف عربي.txt',bytes((i*7)%256 for i in range(700)));put('expected-fat/DIR/INNER.TXT',b'Owned nested FAT file\n');put('expected-fat/EMPTY.TXT',b'')
sys.path.insert(0,str(R/'.downloads/checkers/pycdlib'));import pycdlib
iso=pycdlib.PyCdlib();iso.new(interchange_level=3);iso.add_fp(BytesIO(small['hello.txt']),len(small['hello.txt']),'/HELLO.TXT;1');iso.write(str(out/'samples/files.iso'));iso.close()
wimin=out/'wim-input/folder';wimin.mkdir(parents=True,exist_ok=True)
for n,b in small.items():p=wimin/n;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(b)
(out/'wim-input/outside.txt').write_text('Not in the selected folder.\n')
wim=out/'samples/files.wim'
if not wim.exists():
 env=dict(os.environ);env.pop('LD_PRELOAD',None);env.pop('LD_LIBRARY_PATH',None)
 subprocess.run([str(R/'app/src/main/jniLibs/arm64-v8a/libwimlib_imagex.so'),'capture',str(out/'wim-input'),str(wim),'--compress=LZX','--threads=1','--check','--quiet'],env=env,check=True,stdout=subprocess.DEVNULL)
put('README.txt',b'''USB Workbench manual test files - data only, NOT operating systems.
Extract this ZIP using Android Files into Downloads. Open USBtests.html for instructions.
Use a DIFFERENT empty TestOutput folder for app outputs. Keep these originals unchanged.
HASHES.txt gives each file's SHA-256 fingerprint: 64 characters followed by its path.
password.zip password: fixture-only. It contains owned.txt.
samples/files.wim has image 1: /folder/hello.txt and other small files; /outside.txt is outside /folder.
samples/fat16.img: raw volume, partition number 0. fat16-mbr.img: full disk image, partition 1.
samples/files.iso contains HELLO.TXT only. It is not bootable, a Windows ISO or a PS2 game.
DMG decoded output must match samples/dmg-expected.img. CHD decoded output must match samples/chd-expected.img.
For 0.16.1 basic split/join tests, use raw-8MiB.img and type a custom 3 MiB part size. The old large/console test ZIPs are unnecessary for these small round trips.
Do not write an image onto a USB containing personal data. Only a clearly labelled empty spare may be erased.
''')
lines=[]
for p in sorted(out.rglob('*')):
 if p.is_file() and p.name!='HASHES.txt' and 'wim-input' not in p.relative_to(out).parts:lines.append(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.relative_to(out).as_posix())
put('HASHES.txt',('\n'.join(lines)+'\n').encode())
with zipfile.ZipFile(R/'artifacts/USB-Test-Files.zip','w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 for p in sorted(out.rglob('*')):
  if p.is_file() and 'wim-input' not in p.relative_to(out).parts:z.write(p,'USB-Test-Files/'+p.relative_to(out).as_posix())
# Stream the optional larger fixture directly into a compressed ZIP: no 300MiB temporary file.
h=hashlib.sha256();chunk=bytes(range(256))*4096
with zipfile.ZipFile(R/'artifacts/USB-Test-Large-File.zip','w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 with z.open('USB-Test-Large-File/large-300MiB.bin','w') as f:
  for i in range(300):f.write(chunk);h.update(chunk)
 z.writestr('USB-Test-Large-File/LARGE-HASHES.txt',h.hexdigest()+'  large-300MiB.bin\n')
 z.writestr('USB-Test-Large-File/README.txt','Optional split/join test. Extracts to 300 MiB; allow 1 GiB for the full round trip. Use part size 256 MiB for two generic .uwp parts. No OS/game/boot content.\n')
print('Generated owned test packs, no network downloads.')

# Larger aligned data only, so the console 1GiB option actually creates multiple parts.
h=hashlib.sha256()
with zipfile.ZipFile(R/'artifacts/USB-Test-Console-File.zip','w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 with z.open('USB-Test-Console-File/console-1100MiB.bin','w') as f:
  for i in range(1100):f.write(chunk);h.update(chunk)
 z.writestr('USB-Test-Console-File/CONSOLE-HASHES.txt',h.hexdigest()+'  console-1100MiB.bin\n')
 z.writestr('USB-Test-Console-File/README.txt','Optional raw console-parts byte test, NOT a game or boot image. Expands to 1100 MiB; allow 4 GiB free for splitting and joining. In the app select 1 GiB part size and output filename test.iso. Verify first, then remove only your generated test outputs before repeating the other layout.\n')
print('Generated optional console multipart boundary fixture.')
